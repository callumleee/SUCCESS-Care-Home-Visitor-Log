CREATE TABLE residents (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    room      VARCHAR(20),
    active    BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE visitors (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    phone     VARCHAR(30)
);

CREATE TABLE visits (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visitor_id  BIGINT    NOT NULL REFERENCES visitors (id),
    resident_id BIGINT    NOT NULL REFERENCES residents (id),
    time_in     TIMESTAMP NOT NULL,
    time_out    TIMESTAMP
);

CREATE INDEX idx_visits_time_in ON visits (time_in);
CREATE INDEX idx_visits_resident ON visits (resident_id);

CREATE TABLE staff_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL
);
